<h1>Configuration</h1>

<p>
	The backend reads its settings from environment variables. When you install from source, the local
	backend reads them from <code>Backend/.env.local</code>, and variables exported in your shell take
	precedence over that file. The pod reads only the database password, the connection string and the
	credentials key from <code>secret.yaml</code>; its other settings are fixed in
	<code>backend-pod.yaml</code>.
</p>

<h2>Settings</h2>
<dl>
	<dt><code>ConnectionStrings__DefaultConnection</code></dt>
	<dd>The PostgreSQL connection string. Required: the backend does not start without it.</dd>

	<dt><code>Credentials__Key</code></dt>
	<dd>
		Encrypts the target API credentials and secret header values ChaosLab stores. A base64, 32-byte
		key: <code>openssl rand -base64 32</code>. Without it, secret values cannot be saved or used. If it
		changes, stored secrets can no longer be read and must be entered again.
	</dd>

	<dt><code>BootstrapSetup__PublicUrl</code></dt>
	<dd>
		The web app's address, used to build the setup link. Defaults to
		<code>http://localhost:5173</code>. Must be an absolute HTTP or HTTPS URL without a query, fragment
		or credentials.
	</dd>

	<dt><code>Reports__Path</code></dt>
	<dd>
		The folder for generated PDF reports. Defaults to <code>reports</code> next to the backend, which is
		<code>Backend/reports/</code> for <code>make start</code>; the pod uses <code>/home/app/reports</code>
		on a volume.
	</dd>

	<dt><code>ASPNETCORE_ENVIRONMENT</code></dt>
	<dd><code>Development</code> in the pod. API reference pages are only served in Development.</dd>
</dl>

<h2>Keep these safe</h2>
<ul>
	<li>Never commit <code>secret.yaml</code> or <code>.env</code> files; only the <code>*.example</code> files belong in git.</li>
	<li>Back up <code>Credentials__Key</code> with the database. A restored database is no use for stored credentials without it.</li>
	<li>Serve ChaosLab over HTTPS when anyone other than you reaches it.</li>
</ul>

<h2>Data volumes</h2>
<p>The pod keeps its data in three volumes, which survive <code>make down</code>:</p>
<ul>
	<li><code>chaoslab-postgres-data</code>: the database.</li>
	<li><code>chaoslab-backend-keys</code>: the keys that sign sign-in cookies; without them everyone is signed out on restart.</li>
	<li><code>chaoslab-backend-reports</code>: PDF reports generated by the pod's backend.</li>
</ul>
